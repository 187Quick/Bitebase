export const FOOD_CATEGORIES = Object.keys(DATA);

export const FOODS = Object.entries(DATA).flatMap(([cat, rows]) =>
  rows.map(([name, kcal, protein, carbs, fat, portion, portionLabel]) => ({
    name, cat, kcal, protein, carbs, fat, portion, portionLabel,
    unit: cat === 'Getränke' ? 'ml' : 'g',
  })));

const BY_NAME = new Map(FOODS.map(f => [f.name, f]));
export const findFood = name => BY_NAME.get(name) || null;

/** Nährwerte für eine Menge in g bzw. ml. */
export function nutrition(food, amount) {
  const k = amount / 100;
  const r1 = n => Math.round(n * 10) / 10;
  return { kcal: Math.round(food.kcal * k), protein: r1(food.protein * k), carbs: r1(food.carbs * k), fat: r1(food.fat * k) };
}

const norm = s => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');

/** Suche nach Name; Treffer am Wortanfang zuerst. */
export function searchFoods(query, cat = null, limit = 40) {
  const q = norm(query.trim());
  let list = cat ? FOODS.filter(f => f.cat === cat) : FOODS;
  if (!q) return list.slice(0, cat ? 200 : limit);
  const words = q.split(/\s+/);
  list = list.filter(f => { const n = norm(f.name); return words.every(w => n.includes(w)); });
  const rank = f => { const n = norm(f.name); return n.startsWith(q) ? 0 : n.split(/[\s(/-]+/).some(p => p.startsWith(words[0])) ? 1 : 2; };
  return list.sort((a, b) => rank(a) - rank(b) || a.name.length - b.name.length).slice(0, limit);
}
